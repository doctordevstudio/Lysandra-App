#!/usr/bin/env python3
"""Generates the shared APP_SECRET and the obfuscated Kotlin file used by the Android app.

usage: python tools/gen_secrets.py https://lysandraapp.onrender.com [path/to/Secrets.kt]

 * prints  APP_SECRET=...  (put it in the Render environment)
 * writes  Secrets.kt      (copy into app/src/main/java/com/drdev/hamza/net/)

The URL and secret are never stored as plain strings in the APK: they are split into
random-sized chunks, XOR-masked with a per-build key stream and re-assembled at runtime.
"""
import secrets
import sys


def mask(data: bytes):
    key = secrets.token_bytes(len(data))
    return [b ^ k for b, k in zip(data, key)], list(key)


def chunks(name, data: bytes):
    enc, key = mask(data)
    out, i, n = [], 0, 0
    while i < len(enc):
        size = secrets.choice([3, 4, 5, 7])
        out.append((enc[i:i + size], key[i:i + size]))
        i += size
        n += 1
    order = list(range(len(out)))
    secrets.SystemRandom().shuffle(order)
    lines = []
    for idx in order:
        e, k = out[idx]
        lines.append(f"        {idx} to (intArrayOf({', '.join(map(str, e))}) to intArrayOf({', '.join(map(str, k))})),")
    return "\n".join(lines)


def main():
    url = (sys.argv[1] if len(sys.argv) > 1 else "https://lysandraapp.onrender.com").rstrip("/")
    dest = sys.argv[2] if len(sys.argv) > 2 else "Secrets.kt"
    secret = secrets.token_urlsafe(36)
    kt = f"""package com.drdev.hamza.net

/** GENERATED by backend/tools/gen_secrets.py – do not edit by hand. */
internal object Secrets {{
    private fun join(parts: List<Pair<Int, Pair<IntArray, IntArray>>>): String {{
        val sb = StringBuilder()
        for ((_, p) in parts.sortedBy {{ it.first }}) {{
            for (i in p.first.indices) sb.append((p.first[i] xor p.second[i]).toChar())
        }}
        return sb.toString()
    }}

    fun baseUrl(): String = join(listOf(
{chunks("url", url.encode())}
    ))

    fun appSecret(): String = join(listOf(
{chunks("sec", secret.encode())}
    ))
}}
"""
    open(dest, "w").write(kt)
    print("APP_SECRET=" + secret)
    print(f"wrote {dest}  (url {url})")


if __name__ == "__main__":
    main()
